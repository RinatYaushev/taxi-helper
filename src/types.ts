// Типи даних taxi-helper

export type Payment = "Готівка" | "Безготівка" | "Комбінована";
export type Zone = "Місто" | "Глухий кут";

export interface Settings {
  gas_consumption_l_100km: number;
  gas_price_per_l: number;
  /** Типовий порожняк (частка від пробігу) — fallback, коли зони немає в мапі. */
  empty_run_coef: number;
  /** Порожняк за зоною призначення (частка від пробігу). Місто → малий (наступне
   *  замовлення поруч), глухий кут → ~1.0 (повертаєшся порожнем). */
  empty_run_by_zone?: Partial<Record<Zone, number>>;
  commission_uklon_pct: number;
  /** Додатковий % за вивід безготівки. Для «Комбінованої» береться лише з
   *  безготівкової частини (див. `combined_balance_share`). */
  commission_cashless_pct: number;
  /** Частка суми, що йде на баланс у «Комбінованій» оплаті, коли розбивка не
   *  збережена в самій поїздці (`amount_balance`). Оцінка, не вимір. */
  combined_balance_share?: number;
  threshold_net_per_km: number;
  marginal_net_per_km: number;
  /** Базова планка чистими за годину — ЄДИНА шкала рішень. */
  target_net_per_hour?: number;
  /** Рік за замовчуванням для старого формату `datetime` ("DD.MM HH:MM"). */
  default_year?: number;
  /** Розрив між замовленнями (хв), більший за який вважається кінцем зміни.
   *  Потрібен, бо зміна може переходити через північ. Типово 240. */
  shift_gap_min?: number;
  /** Модель тарифу Uklon: сума ≈ base + per_km×км (калібрується регресією).
   *  Довідкова: показує, де тариф перестає покривати наш поріг. */
  uklon_fare?: {
    base: number;
    per_km: number;
  };
  /** ВИМІРЯНА модель циклу замовлення: `хв = base_min + per_km_min × км`.
   *  Калібрується з інтервалів між стартами сусідніх замовлень (`npm run calibrate`),
   *  тому вже враховує подачу, чекання, передачу і РЕАЛЬНЕ репозиціонування —
   *  порожняк назад окремо додавати НЕ можна (це подвійний рахунок). */
  cycle_model?: {
    base_min: number;
    per_km_min: number;
    by_zone?: Partial<Record<Zone, { base_min: number; per_km_min: number }>>;
  };
  dead_end_areas: string[];
  live_areas: string[];
  /** Далекі міста/смт (міжміський дальняк) — це НЕ глухий кут, окрема логіка. */
  long_haul_areas: string[];
}

export interface Trip {
  /** "YYYY-MM-DD HH:MM" (канон) або старе "DD.MM HH:MM" — обидва читає `time.ts`. */
  datetime: string;
  payment: Payment;
  amount: number;
  /** Скільки з суми пішло на баланс (для «Комбінованої»). Саме з цієї частини
   *  береться `commission_cashless_pct`. Якщо не задано — оцінка з settings. */
  amount_balance?: number;
  distance: number;
  /** Відстань подачі (км) до клієнта — маршрутна, як показує Uklon у момент
   *  пропозиції. Опційно: старі поїздки без цих даних. */
  pickup_km?: number;
  /** Час підльоту (хв) до клієнта — те, що Uklon показує поруч із відстанню. */
  pickup_min?: number;
  from: string;
  to: string;
  zone: Zone;
  /** Зона проставлена **вручну**, всупереч `inArea(to, dead_end_areas)`.
   *  Потрібна, бо адреса не завжди все каже: «ТЦ Епіцентр (Зарванці)» формально
   *  в списку тупиків, але звідти є зворотний потік і це фактично місто;
   *  «Музей-садиба Пирогова» навпаки — тупик без локалітета в дужках, який
   *  правило побачити не може. Без цього поля валідатор вічно лаявся б на
   *  свідомі рішення, і його швидко перестали б читати. */
  zone_manual?: boolean;
  /** Джерело замовлення. Не задано = взято одним із постійних слотів
   *  Автопілота (типовий випадок). "Ефір" — водій обрав вручну зі стрічки,
   *  в обхід фільтра: найчастіше щоб вибратись із глухого кута (під фільтр
   *  нічого не потрапляло), або на високому попиті обрав сам. "Ланцюг" —
   *  водій вимкнув обмеження фільтра й узяв БУДЬ-ЯКЕ замовлення в режимі
   *  Цикл, теж найчастіше щоб вибратись із глухого кута, де фільтр мовчить. */
  source?: "Фільтр" | "Ефір" | "Ланцюг";
}

/**
 * Показана пропозиція — прийнята або відхилена.
 *
 * Це ЄДИНЕ джерело, яке бачить те, чого не бачать `trips`: **що ми відкидаємо**.
 * Уся оптимізація фільтрів досі будувалась на цензурованій вибірці (лише
 * прийняті поїздки, вже відібрані інтуїцією водія). Журнал пропозицій закриває
 * одразу три питання:
 *   • розподіл `pickup_km` — радіус перестає бути здогадкою;
 *   • ціна відмови — скільки коштує звуження фільтра;
 *   • правило фільтра — `max` чи адитивна модель (вони розрізняються на
 *     конкретних сумах, і журнал ловить це за кілька змін).
 */
export interface Offer {
  /** "YYYY-MM-DD HH:MM" — коли пропозицію показали. */
  datetime: string;
  amount: number;
  distance: number;
  /** Відстань подачі, км — Uklon показує її в самій пропозиції. */
  pickup_km?: number;
  /** Час підльоту, хв. */
  pickup_min?: number;
  /** Призначення (можна коротко — лише щоб визначити зону). */
  to?: string;
  zone?: Zone;
  /** Прийняв? `false` — відмовився або пропустив. */
  accepted: boolean;
  /** Звідки прийшла: авто-фільтр, Ефір чи «додаткова» від платформи. */
  source?: "Фільтр" | "Ефір" | "Додаткове";
  /** Чому відмовився — вільним текстом. */
  reason?: string;
}

/**
 * Простій — проміжок, коли ти був вільний, але замовлення не надходило.
 * Доповнює `offers`: там видно відмови, тут — тишу.
 */
export interface Idle {
  datetime: string;
  /** Скільки хвилин простояв без замовлення. */
  minutes: number;
  zone?: Zone;
  /** Який радіус подачі стояв у фільтрі під час простою, км. */
  radius_km?: number;
  note?: string;
}

export interface Data {
  settings: Settings;
  trips: Trip[];
  /** Журнал показаних пропозицій (прийнятих і відхилених). */
  offers?: Offer[];
  /** Ручні записи простоїв. */
  idles?: Idle[];
}

export type Recommendation = "бери" | "думай" | "пропускай";

export interface Computed {
  gas: number;
  commission: number;
  net: number;
  grossPerKm: number;
  netPerKm: number;
  /** Оцінка тривалості замовлення (хв): ВИМІРЯНИЙ цикл (старт цього → старт
   *  наступного), тобто вже з подачею/чеканням/репозиціонуванням. */
  timeMin: number;
  /** Чистими за годину — головна метрика для водія (час дорожчий за газ на ГБО). */
  netPerHour: number;
  rating: "OK" | "погана";
  rec: Recommendation;
  /** Призначення в межах дальняку (long_haul_areas) — міжміський, окрема логіка. */
  longHaul: boolean;
}

export type Row = Trip & Computed;

/**
 * Один із 3 **постійних** слотів Автопілота — прямий переклад у поля фільтра Uklon.
 * Усі три ввімкнені завжди: фільтри об'єднуються за АБО, тож строгий слот нічого
 * не блокує (лише додає), а перемикання «пік/затишшя» робить за тебе сама
 * зайнятість — коли ти в дорозі, м'якший слот просто не має шансу спрацювати.
 *
 * ⚠️ Кожне поле тут — **реальне поле форми Uklon**. Нічого, що неможливо ввести
 * у застосунок, у слоті бути не повинно (на цьому свого часу згорів шар «режимів»
 * з афінним порогом `A + B×км`, якого у формі просто немає).
 */
export interface Slot {
  id: string;
  name: string;
  icon: string;
  /** Роль слота людською мовою. */
  role: string;
  /** «Мін. ціна ₴/км», місто. */
  price_km: number;
  /** «Мін. ціна ₴/км», передмістя. undefined → тумблер «Лише по місту». */
  price_km_suburb?: number;
  /** «Км у мінімалці» — головний важіль проти коротких: поріг рахується
   *  від max(дистанція, це число). */
  km_in_min: number;
  /** «Мін. вартість» замовлення. */
  min_order: number;
  /** «Звідки → Відстань»: максимальний радіус подачі, км. */
  max_pickup_km: number;
  city_only: boolean;
  /** Діагностика підбору: наскільки стабільний цей поріг (див. `deriveSlots`). */
  stability?: SlotStability;
}

/**
 * Наскільки поріг слота — сигнал, а не випадковість конкретних рядків.
 * Рахується бутстрепом ПО ДНЯХ (не по поїздках: сусідні замовлення одного дня
 * корельовані попитом).
 */
export interface SlotStability {
  /** Діапазон цін, що дає ≥ (1−tol) від максимуму захопленого надлишку. */
  plateauLo: number;
  plateauHi: number;
  /** Частка бутстрепів, де оптимум лишається в межах плато, %. */
  agreePct: number;
}

/** Результат бектесту набору слотів на історії. */
export interface SlotStat {
  pass: number;
  cut: number;
  /** ₴/год прийнятих (за виміряним циклом). */
  phPass: number;
  /** ₴/год відсіяних — скільки коштує відмова. */
  phCut: number;
  /** Чистими з прийнятих, грн. */
  netPass: number;
  /** Чистими з відсіяних, грн — це втрата, якщо звільнений час НЕ заповниться. */
  netCut: number;
  /** Прийнято поїздок у глухі кути. */
  deadEnds: number;
}
